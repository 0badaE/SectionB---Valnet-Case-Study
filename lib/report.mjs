// Markdown reports written to out/.

export function ingestReport(docs, chunks, asOf) {
  const retrievableDocs = new Set(chunks.map(c => c.doc_id)).size;
  const lines = [
    '# Ingestion report',
    '',
    `As of ${asOf}. ${docs.length} documents in, ${retrievableDocs} retrievable, ${chunks.length} chunks.`,
    '',
    '| doc | source_type | tier | status | reasons / flags |',
    '|---|---|---|---|---|',
  ];
  for (const doc of docs) {
    const notes = [...doc.reasons, ...doc.flags].join('<br>').replace(/\|/g, '/');
    lines.push(`| ${doc.doc_id} | ${doc.meta.source_type} | ${doc.trust_tier ?? '-'} | **${doc.status}** | ${notes} |`);
  }
  return lines.join('\n') + '\n';
}

function answerSection(result, persona) {
  const { trace } = result;
  const lines = [
    `## ${result.q_id} · ${persona.display_name} (${persona.persona_id}, personalization ${persona.personalization_opt_in ? 'on' : 'off'})`,
    '',
    `> ${result.message}`,
    '',
    result.answer,
    '',
    `- **Route:** ${trace.route}${trace.guards.length ? ` · guards: ${trace.guards.join('; ')}` : ''}`,
    `- **Citations:** ${result.citations.join(', ') || 'none'}`,
    `- **Retrieved:** ${trace.retrieval ? trace.retrieval.results.join(', ') || 'nothing above threshold' : 'skipped (crisis route: no retrieval, no model call)'}`,
  ];
  if (trace.personalization) {
    lines.push(`- **Personalization:** ${trace.personalization.note} Facts: \`${JSON.stringify(trace.personalization.facts_sent)}\``);
  }
  if (trace.calculators.length) lines.push(`- **Calculators:** ${trace.calculators.join(', ')}`);
  if (trace.gaps.length) lines.push(`- **Coverage gaps:** ${trace.gaps.join(', ')}`);
  const payload = result.prompt ? (result.promptHasPII ? 'YES' : 'no') : 'no model call';
  lines.push(`- **Output check:** ${result.check.ok ? 'pass' : result.check.problems.join('; ')} · PII in provider payload: ${payload}`);
  lines.push(`- **Eval:** ${result.failures.length ? `FAIL: ${result.failures.join('; ')}` : 'PASS'}`);
  return lines.join('\n');
}

export function answersReport(results, personas, asOf) {
  const header = [
    '# Answers to the 15 evaluation questions',
    '',
    `Generated by \`node run.mjs\`. As of ${asOf}. The final wording step is mocked (see lib/mock-generator.mjs);`,
    'retrieval, guards, calculators and checks are real.',
  ].join('\n');
  const sections = results.map(r => answerSection(r, personas[r.persona_id]));
  return [header, ...sections].join('\n\n') + '\n';
}
